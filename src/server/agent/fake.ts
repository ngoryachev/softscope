/**
 * `SchemaAgent` without Claude: a scripted reply per scope, plus a call log.
 *
 * Used by every test (no tokens, no network) and by `SOFTSCOPE_FAKE_AGENT=1` for UI work.
 */
import { emptyAgentGraph, type AgentGraph } from '../../shared/agent-schema';
import type { Level } from '../../shared/graph';
import { AgentError, type AgentActivity, type GenerateRequest, type SchemaAgent } from './types';

export type ScriptKey = `${Level}:${string}`;

export function scriptKey(level: Level, scopeId: string): ScriptKey {
  return `${level}:${scopeId}`;
}

export interface FakeSchemaAgentOptions {
  /** Reply per `${level}:${scopeId}`. */
  replies?: Record<string, AgentGraph>;
  /** Used when no scripted reply matches. Defaults to an empty graph. */
  fallback?: (req: GenerateRequest) => AgentGraph;
  /** Throw instead of falling back, to assert a scope is never generated. */
  strict?: boolean;
  /** Artificial delay, to exercise in-flight de-duplication and cancel. */
  delayMs?: number;
  /** Scripted tool activity per `${level}:${scopeId}`, reported through `req.onProgress`. */
  progress?: Record<string, AgentActivity[]>;
}

export class FakeSchemaAgent implements SchemaAgent {
  readonly name = 'fake';
  /** Every request, in order — the test asserts how often the agent was reached. */
  readonly calls: GenerateRequest[] = [];
  private readonly replies: Map<string, AgentGraph>;
  private readonly progress: Map<string, AgentActivity[]>;

  constructor(private readonly opts: FakeSchemaAgentOptions = {}) {
    this.replies = new Map(Object.entries(opts.replies ?? {}));
    this.progress = new Map(Object.entries(opts.progress ?? {}));
  }

  callsFor(level: Level, scopeId: string): number {
    return this.calls.filter((c) => c.scope.level === level && c.scope.id === scopeId).length;
  }

  set(level: Level, scopeId: string, graph: AgentGraph): void {
    this.replies.set(scriptKey(level, scopeId), graph);
  }

  setProgress(level: Level, scopeId: string, events: AgentActivity[]): void {
    this.progress.set(scriptKey(level, scopeId), events);
  }

  async generate(req: GenerateRequest): Promise<AgentGraph> {
    this.calls.push(req);
    if (req.signal?.aborted) throw new AgentError('The analysis was cancelled.', 'cancelled');
    for (const event of this.progress.get(scriptKey(req.scope.level, req.scope.id)) ?? []) {
      req.onProgress?.(event);
    }
    if (this.opts.delayMs) await abortableDelay(this.opts.delayMs, req.signal);
    const scripted = this.replies.get(scriptKey(req.scope.level, req.scope.id));
    if (scripted) return structuredClone(scripted);
    if (this.opts.strict) {
      throw new AgentError(`FakeSchemaAgent has no reply for ${req.scope.level}:${req.scope.id}`);
    }
    return this.opts.fallback?.(req) ?? emptyAgentGraph();
  }
}

/** Waits `ms`, or rejects the way the real agent does when the request is aborted. */
function abortableDelay(ms: number, signal?: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    const onAbort = () => {
      clearTimeout(timer);
      reject(new AgentError('The analysis was cancelled.', 'cancelled'));
    };
    const timer = setTimeout(() => {
      signal?.removeEventListener('abort', onAbort);
      resolve();
    }, ms);
    signal?.addEventListener('abort', onAbort, { once: true });
  });
}

/**
 * A plausible reply derived from the index alone — enough to click through the UI with
 * `SOFTSCOPE_FAKE_AGENT=1`. Not an analysis: every node points at a real file so that
 * validation keeps it, and every edge is marked unconfirmed because nothing was read.
 */
export function indexDerivedReply(req: GenerateRequest): AgentGraph {
  const { index, scope } = req;
  const graph = emptyAgentGraph();
  graph.notes.push(
    'Generated by the fake agent from the repository index only. No code was analyzed.',
  );

  const inScope = (file: string) =>
    scope.paths.includes('.') || scope.paths.some((p) => file === p || file.startsWith(`${p.replace(/\/+$/, '')}/`));

  if (scope.level === 'L4') {
    // The workspace packages are the applications; the root package is one too unless
    // workspaces took over. A nested package.json that is not a workspace member (a
    // fixture, a vendored copy) is neither.
    const workspaces = index.packages.packages.filter((p) => p.workspace);
    const packages = workspaces.length > 0 ? workspaces : index.packages.packages.filter((p) => p.dir === '.');
    for (const pkg of packages) {
      const manifest = pkg.dir === '.' ? 'package.json' : `${pkg.dir}/package.json`;
      graph.nodes.push({
        slug: pkg.name.replace(/[^a-zA-Z0-9]+/g, '-'),
        kind: pkg.workspace ? 'package' : 'application',
        title: pkg.name,
        summary: `Package declared at ${manifest}.`,
        evidence: [{ file: manifest, startLine: 1, endLine: 1, note: 'package manifest' }],
        boundary: false,
        subsystemId: '',
        memberOf: [],
        paths: [pkg.dir === '.' ? 'src' : pkg.dir],
        hasDetail: true,
      });
    }
    for (const external of index.imports.externals.slice(0, 4)) {
      const user = index.imports.files.find((f) => f.external.includes(external.name));
      if (!user) continue;
      graph.nodes.push({
        slug: `ext-${external.name.replace(/[^a-zA-Z0-9]+/g, '-')}`,
        kind: 'external-dependency',
        title: external.name,
        summary: `External dependency imported by ${external.count} files.`,
        evidence: [{ file: user.file, startLine: 1, endLine: 1, note: 'imported here' }],
        boundary: true,
        subsystemId: '',
        memberOf: [],
        paths: [],
        hasDetail: false,
      });
    }
  } else {
    const dirs = new Map<string, string[]>();
    for (const file of index.codeFiles.filter(inScope)) {
      const dir = file.includes('/') ? file.slice(0, file.lastIndexOf('/')) : '.';
      const group = dirs.get(dir);
      if (group) group.push(file);
      else dirs.set(dir, [file]);
    }
    for (const [dir, files] of [...dirs].slice(0, 12)) {
      graph.nodes.push({
        slug: dir.replace(/[^a-zA-Z0-9]+/g, '-') || 'root',
        kind: 'module-group',
        title: dir,
        summary: `${files.length} source files under ${dir}.`,
        evidence: [{ file: files[0]!, startLine: 1, endLine: 1, note: 'first file of the group' }],
        boundary: false,
        subsystemId: '',
        memberOf: [],
        paths: [dir],
        // A module group at L3 can be opened into its L2, so the UI's whole path can be
        // clicked through without Claude.
        hasDetail: scope.level === 'L3',
      });
    }
  }

  const slugs = graph.nodes.filter((n) => !n.boundary).map((n) => n.slug);
  for (let i = 1; i < slugs.length; i += 1) {
    graph.edges.push({
      from: slugs[0]!,
      to: slugs[i]!,
      kind: 'unknown',
      label: '',
      evidence: [],
      confirmed: false,
      reason: 'the fake agent does not read code',
    });
  }
  return graph;
}
