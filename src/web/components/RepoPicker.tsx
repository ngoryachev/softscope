/** First screen: the path of the repository to explore. */
import { useState } from 'react';

export interface RepoPickerProps {
  busy: boolean;
  error: string | null;
  onOpen: (path: string) => void;
}

export function RepoPicker({ busy, error, onOpen }: RepoPickerProps) {
  const [path, setPath] = useState('');
  return (
    <div className="sz-picker">
      <h1>SoftZoom</h1>
      <p className="sz-muted">
        Point it at a local TypeScript or JavaScript repository. The schemas are generated by Claude
        through your local Claude Code login, one area at a time, only when you open it.
      </p>
      <form
        onSubmit={(e) => {
          e.preventDefault();
          if (path.trim()) onOpen(path.trim());
        }}
      >
        <input
          value={path}
          onChange={(e) => setPath(e.target.value)}
          placeholder="/path/to/repository"
          spellCheck={false}
          autoFocus
        />
        <button type="submit" className="sz-button" disabled={busy || path.trim().length === 0}>
          {busy ? 'Opening…' : 'Open'}
        </button>
      </form>
      {error ? <p className="sz-warn">{error}</p> : null}
      <p className="sz-muted">
        You can also start the server with the path: <code>npm start -- /path/to/repository</code>
      </p>
    </div>
  );
}
